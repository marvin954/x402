/**
 * Business Due Diligence Workflow — POST /api/workflows/due-diligence
 *
 * Researches a company + website, analyzes public reputation signals,
 * news, competitors, identifies risks and positive indicators.
 *
 * Clearly labels: verified findings, public information, AI-generated analysis,
 * and unknown/unverified information.
 */
import { webSearch, scrape } from "../../lib/workflow-utils.js";
import { chatJson } from "../../lib/workflow-utils.js";
import { success, withMeta } from "../../lib/response.js";

export async function dueDiligence(input, req) {
  const { company, website, include_competitor_analysis = true } = input;

  if (!company && !website) {
    return { success: false, error: { code: "VALIDATION_ERROR", message: 'Either "company" or "website" is required' } };
  }

  const targetName = company || (website ? extractHostname(website) : "");

  // Step 1: Website analysis
  let webData = null;
  if (website) {
    try { webData = await scrape(website); } catch (err) {
      console.error("[due-diligence] scrape error:", err.message);
    }
  }

  // Step 2: Web searches
  const searchQueries = [
    targetName,
    targetName + " reviews",
    targetName + " " + (website ? extractHostname(website).replace(/^www\./, "") : ""),
  ];
  const searchResults = [];
  for (const q of searchQueries) {
    try {
      const r = await webSearch(q, { maxResults: 8 });
      if (r.length > 0) searchResults.push(...r.map((x) => ({ query: q, ...x })));
    } catch {}
  }

  // Step 3: News search
  let newsResults = [];
  try { newsResults = await webSearch(targetName + " news", { maxResults: 8 }); } catch {}

  // Step 4: Competitor search (optional)
  let compResults = [];
  if (include_competitor_analysis) {
    try { compResults = await webSearch(targetName + " competitor OR alternative", { maxResults: 10 }); } catch {}
  }

  // Step 5: AI synthesis
  const synthesisInput = {
    target: targetName,
    website,
    webData: webData ? { title: webData.title, description: webData.description, technologies: webData.technologies, image: webData.image } : null,
    searchResults: searchResults.slice(0, 15).map((r) => ({ query: r.query, title: r.title, url: r.url, snippet: r.snippet?.slice(0, 200) })),
    newsResults: newsResults.slice(0, 5).map((r) => ({ title: r.title, url: r.url, snippet: r.snippet?.slice(0, 200) })),
    competitorResults: compResults.slice(0, 5).map((r) => ({ title: r.title, url: r.url, snippet: r.snippet?.slice(0, 200) })),
  };

  let analysis;
  try {
    analysis = await chatJson([
      { role: "system", content: "You are a due diligence analyst. Based on the information below, generate a due diligence summary. Return a JSON object with: executive_summary (2-3 sentences), company_overview, verified_findings (array of {fact, source}), positive_indicators (array of {indicator, evidence}), risk_factors (array of {risk, severity low/medium/high, evidence}), unknown_information (array of {what_is_unknown, why_it_matters}), competitor_context (array or empty), recommended_next_steps (array of {step, rationale}), overall_assessment (2-3 sentences with appropriate caveats). Separate verified facts from AI analysis. Be honest about limitations." },
      { role: "user", content: JSON.stringify(synthesisInput, null, 2) },
    ], { temperature: 0.2, max_tokens: 3072 });
  } catch (err) {
    console.error("[due-diligence] AI error:", err.message);
    analysis = {};
  }

  return {
    success: true,
    data: Object.assign({}, analysis || {}, {
      target_name: targetName,
      website,
      research_generated_at: new Date().toISOString(),
      data_sources: [
        { type: "website_scan", available: !!website, result: webData ? "success" : "n/a", title: webData?.title || null },
        { type: "web_search", queries: searchQueries.length, total_results: searchResults.length },
        { type: "news_search", results: newsResults.length },
        { type: "competitor_search", results: include_competitor_analysis ? compResults.length : 0 },
      ],
      labelled_information: {
        verified_findings: webData ? [{ fact: "Website " + website + " is accessible", source: "direct_scan", label: "VERIFIED" }] : [],
        public_information: searchResults.slice(0, 10).map((r) => ({ ...r, label: "PUBLIC_INFO" })),
        ai_generated_analysis: Object.keys(analysis || {}).length > 0 ? { label: "AI_ANALYSIS", note: "Analysis generated by AI based on public information — directional, not definitive" } : null,
        unknown_or_unverified: [{ item: "Financial health", status: "unknown", label: "UNKNOWN", note: "Not assessable from public web search" }, { item: "Internal operations", status: "unknown", label: "UNKNOWN", note: "Not publicly available" }],
      },
    }),
    metadata: { completedAt: new Date().toISOString() },
  };
}

function extractHostname(url) {
  try { return new URL(url).hostname.replace(/^www\./, ""); } catch { return url; }
}
